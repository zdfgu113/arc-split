async (page) => {
  const failures = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  page.on('pageerror', error => failures.push(error.message));
  await page.addInitScript(() => { window.__walletRequests = []; window.ethereum = { request: async (request) => { window.__walletRequests.push(request.method); throw Object.assign(new Error('User rejected request'), { code: 4001 }); }, on() {} }; });
  await page.goto(new URL(page.url()).origin);
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.getByRole('button', { name: '移除第 3 位成员', exact: true }).click();
  await page.getByRole('textbox', { name: '第 1 位成员分账比例', exact: true }).fill('70');
  await page.getByRole('textbox', { name: '第 2 位成员分账比例', exact: true }).fill('30');
  await page.getByRole('textbox', { name: '分账总额', exact: true }).fill('10');
  check((await page.locator('#receipt-members').innerText()).includes('7.00'), '70% payout missing');
  check((await page.locator('#receipt-members').innerText()).includes('3.00'), '30% payout missing');
  await page.getByRole('button', { name: '连接钱包', exact: true }).click();
  check(await page.evaluate(() => window.__walletRequests.length === 0), 'Demo must not request a wallet');
  await page.getByRole('textbox', { name: '第 1 位成员分账比例', exact: true }).fill('69');
  check(await page.locator('#review-button').isDisabled(), 'Invalid total ratio must disable payment');
  await page.getByRole('textbox', { name: '第 1 位成员分账比例', exact: true }).fill('70');
  await page.getByRole('textbox', { name: '分账总额', exact: true }).fill('0.000001');
  check(await page.locator('#review-button').isDisabled(), 'Zero micro payout must disable payment');
  await page.getByRole('textbox', { name: '分账总额', exact: true }).fill('10');
  await page.getByRole('button', { name: '预览这笔分账', exact: true }).click();
  check(await page.locator('#review-dialog').isVisible(), 'Review dialog missing');
  await page.getByRole('button', { name: '演示这笔分账', exact: true }).click();
  check((await page.locator('#history-items').innerText()).includes('仅演示，未付款'), 'Demo history must not claim a payment');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '↓ 导出分账明细', exact: true }).click();
  const download = await downloadPromise;
  check(download.suggestedFilename().endsWith('.csv'), 'CSV download missing');
  await download.saveAs('output/playwright/split-export.csv');
  await page.reload();
  check((await page.locator('#history-items').innerText()).includes('仅演示，未付款'), 'History did not persist');
  await page.locator('#mode').selectOption('testnet');
  check(await page.locator('#review-button').isDisabled(), 'Live form must reject empty recipient addresses');
  check(await page.locator('#address-0').inputValue() === '', 'Sample recipient must be cleared on live mode');
  await page.getByRole('button', { name: '连接钱包', exact: true }).click();
  check((await page.locator('#toast').innerText()).includes('取消'), 'Wallet rejection must be handled');
  check(!(await page.evaluate(() => window.__walletRequests)).includes('eth_sendTransaction'), 'Smoke test must not send any transaction');
  await page.locator('#mode').selectOption('demo');
  await page.getByRole('textbox', { name: '第 1 位成员名称', exact: true }).fill('<img src=x onerror=alert(1)>');
  check(await page.locator('#receipt-members img').count() === 0, 'Nickname must be escaped');
  await page.getByRole('button', { name: '加载示例', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/arc-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile layout overflows');
  await page.locator('.mobile-settings').click();
  check(await page.locator('#settings-dialog').isVisible(), 'Mobile settings must be reachable');
  await page.getByRole('button', { name: '关闭合约设置', exact: true }).click();
  await page.evaluate(() => localStorage.setItem('arc-split-history-v1', JSON.stringify([{id:'0x'+'a'.repeat(64),mode:'testnet',status:'pending',note:'待核查的付款',total:'1000000',date:new Date().toISOString(),payouts:[],fromBlock:'1'}])));
  await page.reload();
  await page.locator('#mode').selectOption('testnet');
  check((await page.locator('#history-items').innerText()).includes('钱包付款状态待核查'), 'An ambiguous wallet result must stay pending');
  check(await page.getByRole('button', { name: '检查确认状态', exact: true }).isVisible(), 'Pending payment without a hash must still have a status check');
  check(await page.locator('#review-button').isDisabled(), 'An unresolved payment must block a new payment');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.screenshot({ path: 'output/playwright/arc-mobile.png', fullPage: true });
  check(failures.length === 0, 'Page errors: ' + failures.join('; '));
  console.log(JSON.stringify({ passed: true, checks: ['70/30 preview', 'ratio validation', 'micro-amount validation', 'no wallet in demo', 'honest demo receipt', 'CSV export', 'history persistence', 'live sample clearing', 'wallet rejection', 'no transaction submission', 'HTML escaping', 'mobile layout', 'mobile settings', 'ambiguous wallet result remains pending', 'pending blocks new payment'], pageErrors: failures }));
}
