async (page) => {
  const errors = [], transactions = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().endsWith('/api/local/transaction')) transactions.push(request.url()); });
  await page.goto('http://127.0.0.1:5178/');
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.locator('#wallet-button').filter({ hasText: '本机 ·' }).waitFor();
  await page.waitForFunction(() => !document.querySelector('#wallet-button').disabled);
  check(await page.locator('#mode').inputValue() === 'testnet', 'Local app must default to testnet');
  check(await page.locator('#local-wallet-details').isVisible(), 'Local wallet details missing');
  const address = await page.locator('#local-wallet-address').innerText();
  check(/^0x[0-9a-fA-F]{40}$/.test(address), 'Full public address missing');
  check((await page.locator('#local-wallet-balance').innerText()).includes('余额：0 USDC'), 'Expected unfunded test wallet');
  check(await page.locator('#testnet-faucet').isVisible(), 'Testnet faucet link missing');
  check(await page.locator('input[type="password"]').count() === 0, 'Password must stay out of the web page');
  await page.locator('#settings-button').click();
  await page.locator('#deploy-contract').click();
  await page.locator('#toast').filter({ hasText: '测试网 USDC 不足' }).waitFor();
  check(transactions.length === 0, 'Unfunded wallet must not request signing');
  await page.getByRole('button', { name: '关闭合约设置', exact: true }).click();
  await page.locator('#mode').selectOption('mainnet');
  check(await page.locator('#local-wallet-details').isHidden(), 'Mode change must invalidate connection');
  await page.locator('#wallet-button').click();
  await page.waitForFunction(() => !document.querySelector('#wallet-button').disabled);
  check(await page.locator('#testnet-faucet').isHidden(), 'Mainnet must not show a testnet faucet');
  await page.locator('#mode').selectOption('demo');
  await page.locator('#wallet-button').click();
  check((await page.locator('#toast').innerText()).includes('不需要钱包'), 'Demo must stay separate');
  await page.locator('#mode').selectOption('testnet');
  await page.locator('#wallet-button').click();
  await page.waitForFunction(() => !document.querySelector('#wallet-button').disabled);
  await page.screenshot({ path: 'output/playwright/local-wallet-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Local wallet card overflows mobile');
  await page.screenshot({ path: 'output/playwright/local-wallet-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1080 });
  check(errors.length === 0, errors.join('; '));
  console.log(JSON.stringify({ passed: true, checks: 12, address, transactions: transactions.length, pageErrors: errors }));
}
